const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const {Firestore}=require('../functions/node_modules/@google-cloud/firestore');
const {purgeCommunityAccount}=require('../functions/communityDeletion');
if(process.env.FIRESTORE_EMULATOR_HOST!=='127.0.0.1:18198'||process.env.GCLOUD_PROJECT!=='demo-invite-expiry')throw Error('Dedicated demo emulator only');
const db=new Firestore({projectId:'demo-invite-expiry'});
after(()=>db.terminate());
test('account cleanup anonymizes own posts, preserves other replies, scopes media and is retry safe',async()=>{
 const uid='community-'+Date.now(),other=uid+'-other',p=db.doc('posts/'+uid),q=db.doc('posts/'+other);
 await p.set({authorUid:uid,authorName:'PRIVATE',title:'PRIVATE',content:'PRIVATE',imageUrls:['PRIVATE'],status:'published',commentCount:2,likeCount:0});
 await p.collection('comments').doc('mine').set({authorUid:uid,content:'PRIVATE'});
 await p.collection('comments').doc('theirs').set({authorUid:other,content:'KEEP'});
 await q.set({authorUid:other,title:'KEEP',status:'published',commentCount:1,likeCount:1});
 await q.collection('comments').doc('mine').set({authorUid:uid,content:'PRIVATE'});
 await q.collection('likes').doc(uid).set({createdAt:new Date()});
 await q.collection('views').doc(uid).set({lastViewedAt:new Date()});
 await db.doc('user_roles/'+uid).set({uid,role:'family'});
 await db.doc('reports/'+uid).set({reporterUid:uid,detail:'PRIVATE'});
 const unrelated=db.doc('other/x/comments/'+uid);await unrelated.set({authorUid:uid,content:'KEEP_UNRELATED'});
 const prefixes=[],bucket={deleteFiles:async args=>prefixes.push(args.prefix)};
 await purgeCommunityAccount({db,bucket,uid});
 assert.equal((await p.get()).data().authorUid,'deleted-account');
 assert.ok(!JSON.stringify((await p.get()).data()).includes('PRIVATE'));
 assert.equal((await p.get()).data().commentCount,1);
 assert.equal((await p.collection('comments').doc('theirs').get()).data().content,'KEEP');
 assert.equal((await q.get()).data().likeCount,0);
 assert.equal((await q.get()).data().commentCount,0);
 assert.equal((await unrelated.get()).exists,true);
 assert.equal((await db.doc('user_roles/'+uid).get()).exists,false);
 assert.equal((await db.doc('reports/'+uid).get()).exists,false);
 await purgeCommunityAccount({db,bucket,uid});
 assert.equal((await p.get()).data().commentCount,1);
 assert.deepEqual(prefixes,[`community_posts/${uid}/`,`community_posts/${uid}/`]);
});
