export const caregiverCopy: Record<Language, CaregiverCopy> = { zh, en, vi, id };

/**
 * Display text for the stored medication "source" labels. The stored values are Chinese
 * sentinels ("藥單辨識", "AI 補充", "藥單資料") and must not change; only the label shown does.
 */
export function sourceLabelText(stored: string, language: Language): string {
  const c = caregiverCopy[language];
  if (stored === "藥單辨識") return c.sourcePrescription;
  if (stored === "AI 補充") return c.sourceAi;
  if (stored === "藥單資料") return c.medSourceDefault;
  return stored;
}

const dateLocales: Record<Language, string> = { zh: "zh-TW", en: "en-US", vi: "vi-VN", id: "id-ID" };

/** "2026年 10月 31日" in Chinese (unchanged format), locale long date elsewhere. */
export function formatLongDate(date: Date, language: Language): string {
  if (Number.isNaN(date.getTime())) return "—";
  if (language === "zh") return `${date.getFullYear()}年 ${date.getMonth() + 1}月 ${date.getDate()}日`;
  try {
    return date.toLocaleDateString(dateLocales[language], { year: "numeric", month: "long", day: "numeric" });
  } catch {
    return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  }
}
