export const communityCopy: Record<Language, CommunityCopy> = { zh, en, vi, id };

/** On-screen label for a stored category value (values stay in Chinese). */
export function communityCategoryLabel(c: CommunityCopy, category: string): string {
  switch (category) {
    case "全部":
      return c.catAll;
    case "照護技巧":
      return c.catTips;
    case "用品資源":
      return c.catSupplies;
    case "經驗交流":
      return c.catExperience;
    default:
      return category;
  }
}

/** On-screen label for a stored report reason value. */
export function communityReasonLabel(c: CommunityCopy, reason: string): string {
  switch (reason) {
    case "廣告或垃圾訊息":
      return c.reasonSpam;
    case "攻擊性言論":
      return c.reasonAbuse;
    case "醫療謠言或錯誤資訊":
      return c.reasonMisinfo;
    case "涉及個人隱私":
      return c.reasonPrivacy;
    case "其他":
      return c.reasonOther;
    default:
      return reason;
  }
}

/** On-screen message for a community image upload error code. */
export function communityUploadErrorMessage(c: CommunityCopy, code: UploadErrorCode): string {
  switch (code) {
    case "tooLarge":
      return c.uploadErrTooLarge;
    case "unauthorized":
      return c.uploadErrUnauthorized;
    case "canceled":
      return c.uploadErrCanceled;
    case "timeout":
      return c.uploadErrTimeout;
    default:
      return c.uploadErrFailed;
  }
}
